export const catalog = { en, ko } as const;
export type TranslationKey = keyof typeof en;

/** Korean "로/으로" particle after a name: Hangul takes 으로 only after a
 *  final consonant other than ㄹ; a trailing digit follows the digit's
 *  Korean reading (십/백/천 endings all take 으로, digits 3·6·0 too);
 *  anything else defaults to 로 ("Space 2로", "GitHub로"). */
export function josaRo(word: string): string {
  const last = word.trim().slice(-1);
  const code = last.codePointAt(0) ?? 0;
  if (code >= 0xac00 && code <= 0xd7a3) {
    const jong = (code - 0xac00) % 28;
    return jong === 0 || jong === 8 ? "로" : "으로";
  }
  if (/[0-9]/.test(last)) return "036".includes(last) ? "으로" : "로";
  if (/[a-zA-Z]/.test(last)) return last === "m" || last === "M" ? "으로" : "로";
  return "로";
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  values: Record<string, string | number> = {}
): string {
  return catalog[language][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    String(values[name] ?? `{{${name}}}`)
  );
}
