import type { LanguagePreference } from "./uiPreferences";

export type AppLanguage = "ko" | "en";

export function resolveLanguage(
  preference: LanguagePreference | undefined,
  deviceLocale: string | null | undefined
): AppLanguage {
  if (preference === "ko" || preference === "en") return preference;
  return /^ko(?:[-_]|$)/i.test(deviceLocale ?? "") ? "ko" : "en";
}

